/*
 * TIM2 update interrupt — fires at exactly 250 Hz.
 *
 * Packet layout (8 bytes, little-endian):
 *   [0] 0xAA          — SOF byte 1
 *   [1] 0x55          — SOF byte 2
 *   [2] seq_lo        — sequence number LSB
 *   [3] seq_hi        — sequence number MSB
 *   [4] val_lo        — int16 sample value LSB
 *   [5] val_hi        — int16 sample value MSB
 *   [6] crc_lo        — CRC-16 CCITT over bytes [2..5], LSB
 *   [7] crc_hi        — CRC-16 CCITT over bytes [2..5], MSB
 *
 * At 115200 baud each 8-byte packet takes ~694 µs.
 * The ISR fires every 4000 µs (250 Hz), so there is plenty of margin.
 */
void HAL_TIM_PeriodElapsedCallback(TIM_HandleTypeDef *htim)
{
    if (htim->Instance != TIM2) return;

    static uint16_t seq = 0;

    /* Fetch next sample from the ECG table */
    int16_t value = ECG_TABLE[ecg_idx];
    ecg_idx = (ecg_idx + 1U) % ECG_TABLE_SIZE;

    /* Build packet */
    uint8_t pkt[8];
    pkt[0] = 0xAA;
    pkt[1] = 0x55;
    pkt[2] = (uint8_t)(seq & 0xFFU);
    pkt[3] = (uint8_t)(seq >> 8);
    pkt[4] = (uint8_t)((uint16_t)value & 0xFFU);
    pkt[5] = (uint8_t)((uint16_t)value >> 8);

    /* CRC covers the 4 payload bytes: seq + value */
    uint16_t crc = crc16_ccitt(&pkt[2], 4);
    pkt[6] = (uint8_t)(crc & 0xFFU);
    pkt[7] = (uint8_t)(crc >> 8);

    seq++;

    /* Transmit — 1 ms timeout is safe: 8 bytes @ 115200 takes ~694 µs */
    HAL_UART_Transmit(&huart3, pkt, 8, 1);
}

